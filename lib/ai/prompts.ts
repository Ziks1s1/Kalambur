type PromptCriterion = {
  code: string;
  title: string;
  description: string;
  maxScore: number;
};

type BuildUserPromptInput = {
  taskId: string;
  subject: string;
  taskNumber: number;
  taskTypeName: string;
  problemText: string;
  criteria: PromptCriterion[];
  criteriaText?: string;
  referenceSolution: string;
  referenceAnswer?: string;
  answerFormat?: string;
  studentComment: string;
};

function buildCriteriaText(criteria: PromptCriterion[], override?: string) {
  if (override?.trim()) {
    return override.trim();
  }

  return criteria.map((criterion) => `${criterion.code}. ${criterion.title} (макс. ${criterion.maxScore})\n${criterion.description}`.trim()).join("\n\n");
}

function buildReferenceText(referenceSolution: string, referenceAnswer?: string) {
  if (referenceAnswer?.trim()) {
    return [`Краткий правильный ответ: ${referenceAnswer.trim()}`, `Эталонное решение: ${referenceSolution.trim()}`].join("\n\n");
  }

  return referenceSolution.trim();
}

function getDefaultAnswerFormat(subject: string, taskNumber: number, taskTypeName: string) {
  const normalizedSubject = subject.toLowerCase();

  if (normalizedSubject.includes("математика")) {
    switch (taskNumber) {
      case 13:
        return "ответ по пунктам а и б с полным решением уравнения";
      case 14:
        return "доказательство в пункте а и вычисление/ответ в пункте б";
      case 15:
        return "развёрнутое решение и итоговый ответ";
      case 16:
        return "математическая модель и итоговый ответ";
      case 17:
        return "доказательство в пункте а и вычисление/ответ в пункте б";
      case 18:
        return "развёрнутое исследование и все значения параметра";
      case 19:
        return "ответы по пунктам а, б и в с обоснованием";
      default:
        return "развёрнутое решение";
    }
  }

  return `развёрнутый ответ по типу задания «${taskTypeName}»`;
}

function buildStudentSolutionText(studentComment: string) {
  const normalized = studentComment.trim();

  if (normalized) {
    return normalized;
  }

  return "Текстовая расшифровка отсутствует; ориентируйся на изображение работы участника.";
}

export function buildSystemPrompt() {
  return [
    "Ты — ИИ-проверяющий развёрнутых ответов ЕГЭ.",
    "Работай строго по переданным критериям и верни результат только в JSON-формате.",
    "Никакого текста вне JSON."
  ].join(" ");
}

export function buildUserPrompt(input: BuildUserPromptInput) {
  const maxScore = input.criteria.reduce((sum, criterion) => sum + criterion.maxScore, 0);
  const criteriaText = buildCriteriaText(input.criteria, input.criteriaText);
  const answerFormat = input.answerFormat?.trim() || getDefaultAnswerFormat(input.subject, input.taskNumber, input.taskTypeName);
  const referenceText = buildReferenceText(input.referenceSolution, input.referenceAnswer);
  const studentSolutionText = buildStudentSolutionText(input.studentComment);

  return `Ты — ИИ-проверяющий развёрнутых ответов ЕГЭ.

Твоя задача: проверить решение участника СТРОГО по переданным критериям оценивания к конкретному заданию.

Работай как эксперт предметной комиссии ФИПИ по следующему протоколу:

1. Проверяй ТОЛЬКО по предоставленным материалам:
- текст задания,
- критерии оценивания,
- эталонный ответ / эталонное решение,
- ответ и решение участника.

2. Главный принцип проверки:
- итоговые баллы выставляются строго по критериям оценивания;
- эталонное решение используется только как ориентир для понимания одного из корректных способов решения;
- решение участника не обязано совпадать с эталоном по форме, последовательности шагов или методу;
- если участник пришёл к верному результату другим способом, оценивай такой способ с точки зрения математической корректности и соответствия критериям;
- нельзя снижать балл только за отличие способа решения от эталонного, если критерии не требуют конкретного метода.

3. Нельзя:
- придумывать дополнительные критерии;
- ставить штрафы, которых нет в критериях;
- ставить баллы "за общее впечатление";
- завышать или занижать оценку из-за стиля, почерка или оформления, если это не предусмотрено критериями;
- требовать дословного совпадения с эталонным решением, если это не указано в критериях;
- засчитывать то, чего нет в работе участника;
- снижать балл за то, что не указано в критериях.

4. Нужно:
- сначала определить, какие именно результаты, элементы ответа или части решения требуются по критериям;
- проверять, достигнуты ли эти результаты у участника;
- выставлять баллы строго по каждому критерию отдельно;
- затем считать итоговый балл как сумму баллов по критериям;
- кратко и точно объяснять, за что поставлен каждый балл и за что он снят;
- ссылаться именно на критерии, а не на общие рассуждения;
- сравнивать решение участника с эталоном только в рамках критериев, а не как с единственно допустимым образцом.

5. Приоритет оценки:
- в первую очередь ориентируйся на то, выполнены ли условия конкретных критериев;
- если критерий основан на результате (например: «получен верно ответ в пункте а», «получены верно ответы в пунктах а и б»), ставь балл именно по факту наличия верного результата;
- если участник получил правильный результат нестандартным, но математически корректным способом, такой результат должен быть засчитан;
- если критерии отдельно требуют обоснование, решение, доказательство, пояснение или промежуточные шаги, проверяй наличие именно этих элементов и не ставь за них баллы, если их нет.

6. Если правильный ответ дан, но по критериям требуется обоснование, решение, пояснение, доказательство или промежуточные шаги, не ставь полный балл только за конечный верный ответ. Следуй критериям строго.

7. Если критерии устроены по результату, например:
- «получен верно ответ в пункте а — 1 балл»,
- «получены верно ответы в пунктах а и б — 2 балла»,
то выставляй баллы, исходя из фактически верно полученных результатов, даже если способ решения отличается от эталонного.
При этом не добавляй требований к методу, если их нет в критериях.

8. Если участник допустил ошибку в ходе решения, отделяй:
- ошибки, которые влияют на итоговый требуемый по критериям результат;
- особенности записи или альтернативный путь, которые не мешают признать результат верным.
Учитывай последующие шаги участника только в той мере, в какой это допускается критериями.

9. Если критерии допускают несколько равноправных способов решения, засчитывай любой корректный способ, даже если он не совпадает с эталоном, но соответствует критериям.

10. Если критерии требуют строгого совпадения ответа, проверяй строгое соответствие.
Если критерии допускают эквивалентные формулировки, преобразования, формы записи или равносильные ответы, засчитывай эквивалентный по смыслу и по математике ответ.

11. При проверке по математике:
- оценивай корректность рассуждений участника по существу;
- допускай иной порядок шагов, иные обозначения и иной способ получения ответа, если они математически верны;
- не считай отличия от эталонного метода ошибкой сами по себе;
- считай ошибкой только то, что реально противоречит математике или не выполняет критерий.

12. Если часть решения нечитаема, оценивай только достоверно различимую часть.
Не додумывай текст.
Обязательно укажи, что часть решения не удалось уверенно распознать.

13. Если приложено изображение решения, используй его как основной источник.
Если есть OCR/текстовая расшифровка, используй её только как вспомогательный материал.
Если между изображением и OCR есть расхождения, приоритет у изображения.

14. Итоговый стиль проверки:
- строго,
- формально,
- без лишней мягкости,
- без домысливания,
- без "поощрительных" баллов,
- максимально близко к экспертной проверке ЕГЭ,
- но без привязки к эталону как к единственно возможному способу решения.

15. Важно:
- не подменяй проверку по критериям сравнением с эталонным ходом решения;
- сначала определи, что именно требуется для получения каждого балла;
- затем проверь, выполнено ли это у участника;
- если результат участника верный и критерий основан именно на результате, засчитывай его даже при нестандартном решении;
- если критерий требует не только результат, но и обоснование, проверяй оба условия отдельно.

16. Верни результат только в заданном JSON-формате.
Никакого текста вне JSON.

ДАННЫЕ ЗАДАНИЯ:
Task ID: ${input.taskId}
Предмет: ${input.subject}
Номер задания: ${input.taskNumber}
Тип задания: ${input.taskTypeName}
Максимальный балл: ${maxScore}

ТЕКСТ ЗАДАНИЯ:
${input.problemText.trim()}

КРИТЕРИИ ОЦЕНИВАНИЯ:
${criteriaText}

ЭТАЛОННЫЙ ОТВЕТ / ЭТАЛОННОЕ РЕШЕНИЕ:
${referenceText}

ФОРМАТ ПРАВИЛЬНОГО ОТВЕТА:
${answerFormat}

ОТВЕТ / РЕШЕНИЕ УЧАСТНИКА:
${studentSolutionText}

ОСОБЫЕ ПРАВИЛА ПРОВЕРКИ:
1. Оцени строго по критериям.
2. Не добавляй собственные требования.
3. Не считай эталонное решение единственно правильным способом.
4. Если участник решил задачу другим способом, проверь этот способ с точки зрения математики и соответствия критериям.
5. Если верный только итоговый ответ, но критерии требуют решение, не ставь полный балл.
6. Если критерий основан на результате, ставь балл по факту верно полученного результата.
7. Если ответ неверный, но есть частично верные элементы, оцени их только если это допускают критерии.
8. Объясняй проверку по каждому критерию отдельно.
9. Итоговый балл должен быть равен сумме выставленных баллов по критериям.
10. Если данных недостаточно для полного зачёта, ставь столько, сколько можно обосновать по критериям, и не больше.

Верни результат строго в JSON по указанной схеме.`;
}
